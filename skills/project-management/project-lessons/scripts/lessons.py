#!/usr/bin/env python3
"""Project-local lesson records. Semantic evidence decisions belong to the agent."""
import argparse
from contextlib import contextmanager
from datetime import date
import json
import os
from pathlib import Path
import re
import sys
import tempfile


MARKER = "<!-- generated by project-lessons; edit JSON records via upsert -->\n"
ID_RE = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*\Z")
CATEGORIES = {"code", "workflow", "operation", "intent"}
STATES = {"confirmed", "pending", "retracted"}


def require(condition, message):
    if not condition:
        raise ValueError(message)


def nonempty(value):
    return isinstance(value, str) and bool(value.strip())


def strings(value, label, minimum=0):
    require(isinstance(value, list) and len(value) >= minimum
            and all(nonempty(x) for x in value), f"{label}: expected nonempty strings")


def read_json(path):
    return json.loads(path.read_text(encoding="utf-8"))


def validate(record):
    require(isinstance(record, dict), "record must be an object")
    require(isinstance(record.get("id"), str) and ID_RE.fullmatch(record["id"])
            and len(record["id"]) <= 80, "invalid lesson id")
    for key in ("title", "scope", "root_cause", "prevention", "solution",
                "adaptation", "review_trigger", "updated_at"):
        require(nonempty(record.get(key)), f"missing {key}")
    date.fromisoformat(record["updated_at"])
    strings(record.get("categories"), "categories", 1)
    require(set(record["categories"]) <= CATEGORIES, "invalid category")
    strings(record.get("keywords"), "keywords")
    require(record.get("validity") in {"active", "needs-review", "retired"}, "invalid validity")
    verification = record.get("verification")
    require(isinstance(verification, dict), "missing verification")
    require(verification.get("status") in {"unverified", "partial", "verified"},
            "invalid verification status")
    strings(verification.get("evidence"), "verification.evidence",
            0 if verification["status"] == "unverified" else 1)
    events = record.get("events")
    require(isinstance(events, list) and len(events) > 0, "events must not be empty")
    ids, refs = set(), set()
    for event in events:
        require(isinstance(event, dict), "event must be an object")
        for key in ("occurrence_id", "date", "summary", "basis"):
            require(nonempty(event.get(key)), f"event missing {key}")
        date.fromisoformat(event["date"])
        require(event.get("state") in STATES, "invalid event state")
        require(event["basis"] in {"user_correction", "direct_evidence", "uncertain"},
                "invalid event basis")
        require(event["state"] != "confirmed" or event["basis"] != "uncertain",
                "confirmed event needs user_correction or direct_evidence")
        strings(event.get("source_refs"), "source_refs", 1)
        require(event["occurrence_id"] not in ids, "duplicate occurrence_id")
        require(not refs.intersection(event["source_refs"]), "duplicate event source; merge first")
        ids.add(event["occurrence_id"])
        refs.update(event["source_refs"])
    return record


def summary(record):
    count = sum(e["state"] == "confirmed" for e in record["events"])
    level = "规则候选评估" if count >= 5 else "重点关注" if count >= 3 else "个案记录" if count else "待确认"
    return {"id": record["id"], "title": record["title"], "confirmed_count": count,
            "level": level, "verification": record["verification"]["status"],
            "validity": record["validity"], "updated_at": record["updated_at"]}


def project_base(project):
    root = Path(project).expanduser().resolve(strict=True)
    require(root.is_dir() and root != Path(root.anchor) and root != Path.home().resolve(),
            "select an actual project directory")
    base = root / "knowledge" / "project-lessons"
    # Refuse shared knowledge targets or symlinked paths, including broken links.
    for item in (root / "knowledge", base):
        require(not item.is_symlink(), f"refusing symlink: {item}")
        require(not item.exists() or item.is_dir(), f"not a directory: {item}")
    if base.exists():
        for folder, dirs, files in os.walk(base, followlinks=False):
            for name in dirs + files:
                require(not (Path(folder) / name).is_symlink(), "symlink inside lesson store")
    return root, base


def records(base):
    result = {}
    for path in sorted((base / "records").glob("*.json")):
        record = validate(read_json(path))
        require(path.stem == record["id"], f"filename/id mismatch: {path}")
        result[record["id"]] = record
    return result


def merge_events(old, incoming):
    merged = json.loads(json.dumps(old, ensure_ascii=False))
    require(isinstance(incoming, list), "events must be a list")
    for new in incoming:
        require(isinstance(new, dict), "event must be an object")
        strings(new.get("source_refs"), "source_refs", 1)
        require(nonempty(new.get("occurrence_id")), "missing occurrence_id")
        matches = [e for e in merged if e["occurrence_id"] == new["occurrence_id"]
                   or set(e["source_refs"]).intersection(new["source_refs"])]
        require(len(matches) <= 1, "event joins multiple old events; resolve ambiguity explicitly")
        if not matches:
            merged.append(new.copy())
        else:
            existing = matches[0]
            stable_id = existing["occurrence_id"]
            source_refs = list(dict.fromkeys(existing["source_refs"] + new["source_refs"]))
            existing.update(new)
            existing.update(occurrence_id=stable_id, source_refs=source_refs)
    return merged


def note(record):
    info = summary(record)
    lines = [MARKER.rstrip(), f"# {record['title']}", "",
             f"- ID：`{record['id']}`", f"- 类型：{', '.join(record['categories'])}",
             f"- 至少 {info['confirmed_count']} 个已确认独立事件；层级：{info['level']}",
             f"- 修法验证：{info['verification']}；适用状态：{info['validity']}",
             f"- 最后复核：{record['updated_at']}", "",
             "次数只用于分层，不表示置信度、规则批准或业务验收。", ""]
    for key, title in (("scope", "适用范围"), ("root_cause", "根因与边界"),
                       ("prevention", "编码或操作前预防"), ("solution", "修复方案"),
                       ("adaptation", "复用时的调整"), ("review_trigger", "复核触发条件")):
        lines += [f"## {title}", "", record[key], ""]
    lines += ["## 验证证据", "", "```json", json.dumps(record["verification"], ensure_ascii=False, indent=2), "```", "",
              "## 独立事件与来源", ""]
    for event in record["events"]:
        lines += [f"### {event['occurrence_id']}", "",
                  f"{event['date']} · {event['state']} · {event['basis']}", "",
                  event["summary"], "", *[f"- {ref}" for ref in event["source_refs"]], ""]
    if record.get("rule_candidate"):
        lines += ["## 规则候选（未自动批准）", "", "```json",
                  json.dumps(record["rule_candidate"], ensure_ascii=False, indent=2), "```", ""]
    return "\n".join(lines) + "\n"


def cell(value):
    return value.replace("|", "\\|").replace("\n", " ").replace("\r", " ")


def index(all_records):
    lines = [MARKER.rstrip(), "# 项目错误经验索引", "",
             "按需检索；普通任务开始不固定查阅。1 次记录，3 次关注，5 次候选评估。",
             "确认次数是可回查事件的下界，候选仍需证据评估与具体条文批准。", "",
             "| 经验 | 关键词 | 确认次数 | 层级 | 修法验证 | 适用状态 | 最后复核 |",
             "|---|---|---:|---|---|---|---|"]
    for lesson_id, record in sorted(all_records.items()):
        info = summary(record)
        lines.append(f"| [{cell(record['title'])}](notes/{lesson_id}.md) | "
                     f"{cell(', '.join(record['keywords']))} | {info['confirmed_count']} | "
                     f"{info['level']} | {info['verification']} | {info['validity']} | "
                     f"{cell(info['updated_at'])} |")
    return "\n".join(lines) + "\n"


def views(base, all_records):
    output = {base / "INDEX.md": index(all_records)}
    output.update({base / "notes" / f"{key}.md": note(value) for key, value in all_records.items()})
    return output


def safe_views(output):
    for path in output:
        require(not path.exists() or path.read_text(encoding="utf-8").startswith(MARKER),
                f"existing file is not a generated view; refusing overwrite: {path}")


def atomic_write(path, content):
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temp = tempfile.mkstemp(prefix=".write-", dir=path.parent)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(content)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temp, path)
    finally:
        if os.path.exists(temp):
            os.unlink(temp)
    return True


@contextmanager
def locked(base):
    # flock releases on process exit; do not delete a lock another writer may hold.
    import fcntl
    base.mkdir(parents=True, exist_ok=True)
    with (base / ".write.lock").open("a") as handle:
        try:
            fcntl.flock(handle, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as error:
            raise ValueError("lesson store busy; another writer is active") from error
        try:
            yield
        finally:
            fcntl.flock(handle, fcntl.LOCK_UN)


def upsert(base, incoming):
    require(isinstance(incoming, dict), "input must be an object")
    lesson_id = incoming.get("id")
    require(isinstance(lesson_id, str) and ID_RE.fullmatch(lesson_id), "invalid lesson id")
    # Validate before creating a store. Re-read under the lock before mutation.
    def prepare(existing):
        previous = existing.get(lesson_id, {})
        updated = {**previous, **incoming}
        updated["events"] = merge_events(previous.get("events", []), incoming.get("events", []))
        if previous and any(key in incoming and incoming[key] != previous.get(key)
                            for key in ("solution", "scope", "root_cause", "adaptation")):
            require("verification" in incoming,
                    "changed repair/scope needs explicit verification status; do not inherit old proof")
        return validate(updated)
    prepare(records(base))
    with locked(base):
        existing = records(base)
        updated = prepare(existing)
        existing[lesson_id] = updated
        output = views(base, existing)
        safe_views(output)
        content = json.dumps(updated, ensure_ascii=False, indent=2) + "\n"
        changed = atomic_write(base / "records" / f"{lesson_id}.json", content)
        for path, body in output.items():
            changed = atomic_write(path, body) or changed
        return {**summary(updated), "changed": changed,
                "note": str(base / "notes" / f"{lesson_id}.md")}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    for command in ("upsert", "search", "show", "check", "rebuild"):
        item = sub.add_parser(command)
        item.add_argument("--project", required=True)
        if command == "upsert":
            item.add_argument("--input", required=True)
        if command == "search":
            item.add_argument("--query", required=True)
            item.add_argument("--include-retired", action="store_true")
        if command == "show":
            item.add_argument("--id", required=True)
    args = parser.parse_args()
    _, base = project_base(args.project)
    if args.command == "upsert":
        result = upsert(base, read_json(Path(args.input)))
    else:
        all_records = records(base)
        if args.command == "show":
            require(args.id in all_records, "lesson not found")
            result = all_records[args.id]
        elif args.command == "search":
            terms = args.query.casefold().split()
            require(bool(terms), "query must not be empty")
            result = []
            for key, value in all_records.items():
                haystack = json.dumps(value, ensure_ascii=False).casefold()
                if (value["validity"] != "retired" or args.include_retired) and all(t in haystack for t in terms):
                    result.append({**summary(value), "note": str(base / "notes" / f"{key}.md")})
        elif args.command == "check":
            errors = [str(path) for path, body in views(base, all_records).items()
                      if (all_records or path.exists())
                      and (not path.exists() or path.read_text(encoding="utf-8") != body)]
            require(not errors, "views out of date; use rebuild: " + ", ".join(errors))
            result = {"ok": True, "lessons": len(all_records)}
        else:
            if not all_records:
                result = {"changed": False, "lessons": 0}
            else:
                with locked(base):
                    all_records = records(base)
                    output = views(base, all_records)
                    safe_views(output)
                    changed = False
                    for path, body in output.items():
                        changed = atomic_write(path, body) or changed
                result = {"changed": changed, "lessons": len(all_records)}
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError, KeyError, TypeError) as error:
        print(json.dumps({"error": str(error)}, ensure_ascii=False), file=sys.stderr)
        sys.exit(2)
